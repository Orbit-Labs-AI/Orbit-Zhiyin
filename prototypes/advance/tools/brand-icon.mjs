// Generates src/js/01-brand.js from the official Orbit logo (docs/design/logo/orbit-*.svg). The App icon and the menu-bar
// item use these vectors as they are, so the demo always shows the published icon. Rerun after the logo changes:
//   node tools/brand-icon.mjs && node build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const logo = path.join(here, '..', '..', '..', 'docs', 'design', 'logo');
const out = path.join(here, '..', 'src', 'js', '01-brand.js');

// The mark's polygons and round end caps, without the colour (fill comes from the caller), as one SVG fragment.
function shapes(file) {
  const svg = fs.readFileSync(path.join(logo, file), 'utf8');
  const g = svg.match(/<g fill="[^"]*"(?: transform="([^"]*)")?>([\s\S]*?)<\/g>/);
  if (!g) throw new Error(file + ': no <g> with the mark');
  const parts = g[2].match(/<(polygon|circle)\b[^>]*\/>/g) || [];
  if (!parts.length) throw new Error(file + ': the mark has no shapes');
  return { body: parts.join(''), transform: g[1] || null, viewBox: svg.match(/viewBox="([^"]*)"/)[1], tile: svg.match(/<rect[^>]*rx="([\d.]+)"[^>]*fill="([^"]*)"/) };
}
const icon = shapes('orbit-icon.svg');           // full-size icon: fine strokes, placed on the 1024 tile
const small = shapes('orbit-mark-small.svg');    // small-size rendition: heavier strokes below 128px and in the menu bar
if (!icon.transform || !icon.tile) throw new Error('orbit-icon.svg: missing tile or mark transform');
const js = `/* ============ brand: the Orbit mark (generated by tools/brand-icon.mjs from docs/design/logo/orbit-*.svg) ============ */
// Do not edit by hand. appIcon(px) = the App icon (warm tile + slate mark, the same in both themes); sizes below 128px use the
// logo's small rendition, which has heavier strokes. GLYPH = the menu-bar item (template image: one colour, follows the menu
// bar text). The page favicon is the same icon.
const ORBIT_TILE = { rx: ${(+icon.tile[1] / 1024 * 100).toFixed(2)}, bg: '${icon.tile[2]}', ink: '#5f6b6f' };   // corner radius in % of the tile
const ORBIT_ICON = '${icon.body}';
const ORBIT_SMALL = '${small.body}';
const ORBIT_T = '${icon.transform}';                 // mark → 1024 tile (logo coordinates are shared by both renditions)
function appIcon(px, o) {
  o = o || {};
  const tile = o.tile ? '<rect width="1024" height="1024" rx="' + (ORBIT_TILE.rx * 10.24).toFixed(1) + '" fill="' + ORBIT_TILE.bg + '"/>' : '';
  return '<svg class="orbit-mark" width="' + px + '" height="' + px + '" viewBox="0 0 1024 1024" aria-hidden="true">' + tile + '<g fill="' + (o.fill || 'var(--orbit)') + '" transform="' + ORBIT_T + '">' + (px >= 128 ? ORBIT_ICON : ORBIT_SMALL) + '</g></svg>';
}
const GLYPH = '<svg class="orbit-mark" width="20" height="16" viewBox="${small.viewBox}" aria-hidden="true"><g fill="currentColor">' + ORBIT_SMALL + '</g></svg>';
(function favicon() {
  try {
    const l = document.createElement('link'); l.rel = 'icon'; l.type = 'image/svg+xml';
    l.href = 'data:image/svg+xml,' + encodeURIComponent(appIcon(64, { tile: true, fill: ORBIT_TILE.ink }).replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" '));
    document.head.appendChild(l);
  } catch (e) { /* no document head: nothing to do */ }
})();
`;
fs.writeFileSync(out, js);
console.log('brand ->', path.relative(process.cwd(), out), '(' + Math.round(js.length / 1024) + ' KB)');
