// Generates src/js/01-brand.js from the official Orbit logo (docs/design/logo/orbit-*.svg). The App icon and the menu-bar
// item use these vectors as they are, so the demo always shows the published icon. Rerun after the logo changes:
//   node tools/brand-icon.mjs && node build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const logo = path.join(here, '..', '..', '..', 'docs', 'design', 'logo');
const out = path.join(here, '..', 'src', 'js', '01-brand.js');

// The mark is one <path> (design coordinates), without the colour (fill comes from the caller).
function shapes(file) {
  const svg = fs.readFileSync(path.join(logo, file), 'utf8');
  const g = svg.match(/<g fill="[^"]*"(?: transform="([^"]*)")?><path d="([^"]+)"\/><\/g>/);
  if (!g) throw new Error(file + ': no <g> with the mark path');
  return { d: g[2], transform: g[1] || null, viewBox: svg.match(/viewBox="([^"]*)"/)[1], tile: svg.match(/<rect[^>]*rx="([\d.]+)"[^>]*fill="([^"]*)"/) };
}
const icon = shapes('orbit-icon.svg');           // the App icon: mark placed on the 1024 tile
const mark = shapes('orbit-mark.svg');           // the same path on its tight canvas (menu bar)
if (!icon.transform || !icon.tile) throw new Error('orbit-icon.svg: missing tile or mark transform');
if (mark.d !== icon.d) throw new Error('orbit-mark.svg and orbit-icon.svg must share one path; rerun docs/design/logo/generate.py');
const js = `/* ============ brand: the Orbit mark (generated by tools/brand-icon.mjs from docs/design/logo/orbit-*.svg) ============ */
// Do not edit by hand. appIcon(px) = the App icon (warm tile + slate mark, the same in both themes), the 1024 icon scaled as a
// whole at every size. GLYPH = the menu-bar item (template image: one colour, follows the menu bar text), the same path on its
// tight canvas. The page favicon is the same icon.
const ORBIT_TILE = { rx: ${(+icon.tile[1] / 1024 * 100).toFixed(2)}, bg: '${icon.tile[2]}', ink: '#5f6b6f' };   // corner radius in % of the tile
const ORBIT_PATH = '<path d="${icon.d}"/>';
const ORBIT_T = '${icon.transform}';                 // mark → 1024 tile
function appIcon(px, o) {
  o = o || {};
  const tile = o.tile ? '<rect width="1024" height="1024" rx="' + (ORBIT_TILE.rx * 10.24).toFixed(1) + '" fill="' + ORBIT_TILE.bg + '"/>' : '';
  return '<svg class="orbit-mark" width="' + px + '" height="' + px + '" viewBox="0 0 1024 1024" aria-hidden="true">' + tile + '<g fill="' + (o.fill || 'var(--orbit)') + '" transform="' + ORBIT_T + '">' + ORBIT_PATH + '</g></svg>';
}
const GLYPH = '<svg class="orbit-mark" width="20" height="16" viewBox="${mark.viewBox}" aria-hidden="true"><g fill="currentColor">' + ORBIT_PATH + '</g></svg>';
(function favicon() {
  try {
    const l = document.createElement('link'); l.rel = 'icon'; l.type = 'image/svg+xml';
    l.href = 'data:image/svg+xml,' + encodeURIComponent(appIcon(64, { tile: true, fill: ORBIT_TILE.ink }).replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" '));
    document.head.appendChild(l);
  } catch (e) { /* no document head: nothing to do */ }
})();
`;
fs.writeFileSync(out, js);
console.log('brand ->', path.relative(process.cwd(), out), '(' + Math.round(js.length / 1024) + ' KB)');
